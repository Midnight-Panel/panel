using Microsoft.EntityFrameworkCore;
using Midnight.ApiServer.Core.Configuration;
using Midnight.ApiServer.Core.Database;
using Midnight.ApiServer.Core.Http;

namespace Midnight.ApiServer.Features.Account.Services;

/// <summary>Stores avatars in storage/avatars. The file type is detected from the content, never from the upload name.</summary>
public class AvatarService
{
    public const long MaxSize = 1024 * 1024;

    private readonly DataContext _context;
    private readonly string _directory;

    public AvatarService(DataContext context, StoragePaths storagePaths)
    {
        _context = context;
        _directory = Path.Combine(storagePaths.Root, "avatars");
    }

    public async Task SetAsync(int userId, Stream content, CancellationToken cancellationToken)
    {
        var user = await _context.Users.FirstOrDefaultAsync(x => x.Id == userId, cancellationToken)
                   ?? throw HttpApiException.NotFound("User not found");

        using var buffer = new MemoryStream();
        await content.CopyToAsync(buffer, cancellationToken);

        if (buffer.Length == 0 || buffer.Length > MaxSize)
            throw HttpApiException.BadRequest("The avatar must be smaller than 1 MB");

        var bytes = buffer.ToArray();
        var extension = DetectExtension(bytes)
                        ?? throw HttpApiException.BadRequest("Only PNG, JPEG and WebP images are allowed");

        Directory.CreateDirectory(_directory);

        // New file name on every upload so browsers don't show a cached old avatar
        var fileName = $"{userId}-{Guid.NewGuid():N}{extension}";
        await File.WriteAllBytesAsync(Path.Combine(_directory, fileName), bytes, cancellationToken);

        DeleteFile(user.AvatarFileName);

        user.AvatarFileName = fileName;
        await _context.SaveChangesAsync(cancellationToken);
    }

    public async Task RemoveAsync(int userId, CancellationToken cancellationToken)
    {
        var user = await _context.Users.FirstOrDefaultAsync(x => x.Id == userId, cancellationToken)
                   ?? throw HttpApiException.NotFound("User not found");

        DeleteFile(user.AvatarFileName);

        user.AvatarFileName = null;
        await _context.SaveChangesAsync(cancellationToken);
    }

    public async Task<(string Path, string ContentType)?> GetAsync(int userId, CancellationToken cancellationToken)
    {
        var fileName = await _context.Users
            .Where(x => x.Id == userId)
            .Select(x => x.AvatarFileName)
            .FirstOrDefaultAsync(cancellationToken);

        if (fileName == null)
            return null;

        var path = Path.Combine(_directory, fileName);

        if (!File.Exists(path))
            return null;

        var contentType = Path.GetExtension(fileName) switch
        {
            ".png" => "image/png",
            ".jpg" => "image/jpeg",
            ".webp" => "image/webp",
            _ => "application/octet-stream"
        };

        return (path, contentType);
    }

    private void DeleteFile(string? fileName)
    {
        if (fileName == null)
            return;

        // File names are generated by us, GetFileName is just a safety net
        var path = Path.Combine(_directory, Path.GetFileName(fileName));

        if (File.Exists(path))
            File.Delete(path);
    }

    internal static string? DetectExtension(ReadOnlySpan<byte> bytes)
    {
        if (bytes.Length >= 8 && bytes[..8].SequenceEqual(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A }))
            return ".png";

        if (bytes.Length >= 3 && bytes[0] == 0xFF && bytes[1] == 0xD8 && bytes[2] == 0xFF)
            return ".jpg";

        if (bytes.Length >= 12 && bytes[..4].SequenceEqual("RIFF"u8) && bytes[8..12].SequenceEqual("WEBP"u8))
            return ".webp";

        return null;
    }
}
