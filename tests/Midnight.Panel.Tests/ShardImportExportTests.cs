using System.Text.Json;
using Midnight.Shared.Http.Shards;

namespace Midnight.Panel.Tests;

public class ShardImportExportTests
{
    [Fact]
    public void ShardExportPackage_SerializesWithCorrectFormatVersion()
    {
        var package = new ShardExportPackage
        {
            FormatVersion = ShardExportPackage.CurrentFormatVersion,
            Collection = new ShardExportCollectionInfo
            {
                Name = "Minecraft",
                Author = "Midnight Team"
            },
            Shard = new ShardExportData
            {
                Name = "Paper",
                Author = "PaperMC",
                Version = "1.20.4",
                StartupCommand = "java -Xmx{{SERVER_MEMORY}}M -jar {{SERVER_JARFILE}}",
                DefaultDockerImage = "ghcr.io/midnightpanel/yolks:java_21",
                DockerImages = new() { ["Java 21"] = "ghcr.io/midnightpanel/yolks:java_21" },
                Variables =
                [
                    new ShardVariableExportData
                    {
                        Name = "Jar File",
                        EnvVariable = "SERVER_JARFILE",
                        DefaultValue = "server.jar",
                        Rules = "required|string"
                    }
                ]
            }
        };

        var json = JsonSerializer.Serialize(package, new JsonSerializerOptions { WriteIndented = true });

        Assert.Contains("\"formatVersion\": \"midnight_shard_v1\"", json);
        Assert.Contains("SERVER_JARFILE", json);
        Assert.Contains("Paper", json);

        var deserialized = JsonSerializer.Deserialize<ShardExportPackage>(json);
        Assert.NotNull(deserialized);
        Assert.Equal("midnight_shard_v1", deserialized.FormatVersion);
        Assert.Equal("Paper", deserialized.Shard.Name);
        Assert.Single(deserialized.Shard.Variables);
    }

    [Fact]
    public void LegacyPtdlFormat_CanBeDetectedAndParsed()
    {
        var legacyJson = """
        {
            "_comment": "DO NOT EDIT THIS FILE DIRECTLY",
            "meta": {
                "version": "PTDL_v2",
                "update_url": null
            },
            "exported_at": "2024-01-01T00:00:00Z",
            "name": "Vanilla Minecraft",
            "author": "support@example.com",
            "description": "The official Minecraft server software.",
            "features": null,
            "docker_images": {
                "Java 17": "ghcr.io/example/java:17"
            },
            "startup": "java -Xms128M -Xmx{{SERVER_MEMORY}}M -jar {{SERVER_JARFILE}}",
            "config": {
                "stop": "stop",
                "startup": {
                    "done": ") Done ("
                },
                "files": {
                    "server.properties": {
                        "parser": "properties",
                        "find": {
                            "server-port": "{{SERVER_PORT}}"
                        }
                    }
                }
            },
            "scripts": {
                "installation": {
                    "script": "#!/bin/bash\necho Installing...",
                    "container": "alpine:3.18",
                    "entrypoint": "bash"
                }
            },
            "variables": [
                {
                    "name": "Server Jar",
                    "description": "Name of jar",
                    "env_variable": "SERVER_JARFILE",
                    "default_value": "server.jar",
                    "user_viewable": true,
                    "user_editable": true,
                    "rules": "required|string|max:20"
                }
            ]
        }
        """;

        using var doc = JsonDocument.Parse(legacyJson);
        var root = doc.RootElement;

        var isLegacy = root.TryGetProperty("meta", out _) || root.TryGetProperty("_comment", out _);
        Assert.True(isLegacy);

        var name = root.GetProperty("name").GetString();
        Assert.Equal("Vanilla Minecraft", name);

        var startup = root.GetProperty("startup").GetString();
        Assert.Contains("SERVER_MEMORY", startup);

        var stop = root.GetProperty("config").GetProperty("stop").GetString();
        Assert.Equal("stop", stop);

        var startupDone = root.GetProperty("config").GetProperty("startup").GetProperty("done").GetString();
        Assert.Equal(") Done (", startupDone);

        var variables = root.GetProperty("variables");
        Assert.Equal(1, variables.GetArrayLength());
        Assert.Equal("SERVER_JARFILE", variables[0].GetProperty("env_variable").GetString());
    }
}
